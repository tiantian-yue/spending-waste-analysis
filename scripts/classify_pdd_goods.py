OTHER = "其他"
CODE_OF = {k: v[0] for k, v in RULES.items()}
CODE_OF[OTHER] = "OTHER"


def classify(title: str) -> tuple[str, str, int]:
    """返回 (大类, 项目分类码, 得分)"""
    best, best_score, code = OTHER, 0, "OTHER"
    for cat, (_code, kws) in RULES.items():
        score = sum(len(kw) for kw in kws if kw in title)
        if score > best_score:
            best, best_score, code = cat, score, CODE_OF[cat]
    return best, code, best_score


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("orders", help="parse_pdd_orders.py 产出的 CSV")
    ap.add_argument("-o", "--out", default="classified.csv")
    args = ap.parse_args()

    rows = list(csv.DictReader(io.open(args.orders, encoding="utf-8-sig")))
    for r in rows:
        cat, code, score = classify(r["商品标题"])
        r["大类"], r["项目分类码"], r["得分"] = cat, code, str(score)

    with io.open(args.out, "w", encoding="utf-8-sig", newline="") as fp:
        w = csv.DictWriter(fp, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)

    valid = [r for r in rows if not r["退款"]]
    dist = collections.Counter(r["大类"] for r in valid)
    print(f"商品行 {len(rows)} 条（有效 {len(valid)}）· 归到「其他」"
          f" {dist.get(OTHER, 0)} 条 = {100*dist.get(OTHER,0)/max(1,len(valid)):.1f}%\n")
    print("=== 大类分布（有效商品行）===")
    for cat, n in dist.most_common():
        print(f"   {cat:<8} {n:>4} 条  {100*n/len(valid):5.1f}%")

    print("\n=== 各类抽样 3 条（自查归类是否离谱）===")
    for cat, _ in dist.most_common(8):
        print(f"  [{cat}]")
        for r in [x for x in valid if x["大类"] == cat][:3]:
            print(f"      {r['商品标题'][:46]}")
    print(f"\n输出 → {os.path.abspath(args.out)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
